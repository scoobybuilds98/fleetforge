    // ─────────────────────────────────────────────────────────────────────────────
    // STEP 4 — Vendors (4).  vendor_type enum is (maintenance,repair,parts,
    // inspection,towing,other) — fuel supplier + finance lender map to 'other'.
    // ─────────────────────────────────────────────────────────────────────────────
    echo "\nStep 4 — Vendors...\n";
    $vendorDefs = [
        'maintenance' => ['name' => 'Fraser Valley Truck & Trailer Repair', 'vendor_type' => 'maintenance', 'contact' => 'Doug McRae',     'city' => 'Abbotsford', 'phone' => '604-555-7100', 'domain' => 'fvtrucktrailer.ca', 'hourly' => '145.00', 'rating' => 5],
        'parts'       => ['name' => 'Pacific Truck Parts Ltd.',             'vendor_type' => 'parts',       'contact' => 'Nadia Petrov',   'city' => 'Surrey',     'phone' => '604-555-7200', 'domain' => 'pacifictruckparts.ca','hourly' => null,    'rating' => 4],
        'fuel'        => ['name' => 'Coastal Fuels Inc.',                   'vendor_type' => 'other',       'contact' => 'Trevor Lund',    'city' => 'Delta',      'phone' => '604-555-7300', 'domain' => 'coastalfuels.ca',   'hourly' => null,    'rating' => 4],
        'finance'     => ['name' => 'BC Equipment Finance Corp.',           'vendor_type' => 'other',       'contact' => 'Janet Soo',      'city' => 'Vancouver',  'phone' => '604-555-7400', 'domain' => 'bcequipfinance.ca', 'hourly' => null,    'rating' => 5],
    ];
    $vendorIds = [];
    foreach ($vendorDefs as $key => $v) {
        $local = strtolower(explode(' ', $v['contact'])[0]);
        $vendorIds[$key] = db_insert('vendors', [
            'name'          => $v['name'],
            'vendor_type'   => $v['vendor_type'],
            'contact_name'  => $v['contact'],
            'email'         => $local . '@' . $v['domain'],
            'phone'         => $v['phone'],
            'city'          => $v['city'],
            'state'         => 'BC',
            'specializations'=> json_encode([$key]),
            'hourly_rate'   => $v['hourly'],
            'rating'        => $v['rating'],
            'currency'      => 'CAD',
            'notes'         => 'Dress-rehearsal vendor.',
            'created_by'    => RS_USER,
        ]);
        printf("  id=%d %-38s (%s)\n", $vendorIds[$key], $v['name'], $v['vendor_type']);
    }

    // ─────────────────────────────────────────────────────────────────────────────
    // STEP 5 — Leases (6, varied lifecycle).  Each references a fresh unit; rates
    // come straight from the unit's template defaults (never 0). Equipment status
    // is synced (active→on_lease, completed→available).
    //
    // Lifecycle map:
    //   L1 just-started (7d ago, 1 sent unpaid invoice)        → dry van
    //   L2 mid-cycle partial (60d, 2 inv: 1 paid 1 outstanding)→ reefer   [E2 target]
    //   L3 mid-cycle current (45d, 2 inv: all paid)            → flatbed
    //   L4 ending soon (end +14d, 2 inv: current/sent)         → step deck
    //   L5 long-term (180d, 6 monthly inv: 5 paid 1 out)       → day-cab tractor
    //   L6 recently closed (returned 10d ago, 1 final paid)    → sleeper tractor
    // ─────────────────────────────────────────────────────────────────────────────
    echo "\nStep 5 — Leases...\n";
    $leasePlan = [
        'L1' => ['label' => 'Just started — dry van',         'cust' => 0, 'unit' => 'T5301', 'status' => 'active',    'start' => rs_days_ago(7),   'end' => rs_days_from_now(358), 'next_bill' => rs_days_from_now(23)],
        'L2' => ['label' => 'Mid-cycle partial — reefer',     'cust' => 1, 'unit' => 'T6201', 'status' => 'active',    'start' => rs_days_ago(60),  'end' => rs_days_from_now(305), 'next_bill' => rs_days_from_now(1)],
        'L3' => ['label' => 'Mid-cycle current — flatbed',    'cust' => 2, 'unit' => 'T4801', 'status' => 'active',    'start' => rs_days_ago(45),  'end' => rs_days_from_now(320), 'next_bill' => rs_days_from_now(15)],
        'L4' => ['label' => 'Ending soon — step deck',        'cust' => 3, 'unit' => 'T3501', 'status' => 'active',    'start' => rs_days_ago(46),  'end' => rs_days_from_now(14),  'next_bill' => rs_days_from_now(14)],
        'L5' => ['label' => 'Long-term — day cab tractor',    'cust' => 6, 'unit' => 'P1001', 'status' => 'active',    'start' => rs_days_ago(180), 'end' => rs_days_from_now(185), 'next_bill' => rs_days_from_now(2)],
        'L6' => ['label' => 'Recently closed — sleeper',      'cust' => 8, 'unit' => 'P2001', 'status' => 'completed', 'start' => rs_days_ago(38),  'end' => rs_days_ago(10),       'return' => rs_days_ago(10)],
    ];
    $leaseIds = [];
    $contractSeq = 0;
    foreach ($leasePlan as $lk => $l) {
        $unit     = $units[$l['unit']];
        $custIdx  = $l['cust'];
        $custDef  = $customerDefs[$custIdx];
        $custId   = $customerIds[$custIdx];
        $tax      = rs_freeze_tax(1);
        $contractSeq++;

        $row = [
            'contract_number'         => sprintf('CN-RHRSL-%04d', $contractSeq),
            'customer_id'             => $custId,
            'equipment_unit_id'       => $unit['id'],
            'customer_name_snapshot'  => $custDef['contact'],
            'company_name_snapshot'   => $custDef['company'],
            'unit_number_snapshot'    => $unit['unit_number'],
            'template_name_snapshot'  => $unit['template_name'],
            'equipment_snapshot_json' => rs_build_equip_snap($unit),
            'status'                  => $l['status'],
            'start_date'              => $l['start'],
            'end_date'                => $l['end'],
            'actual_return_date'      => $l['return'] ?? null,
            'daily_rate'              => $unit['daily_rate'],
            'weekly_rate'             => $unit['weekly_rate'],
            'monthly_rate'            => $unit['monthly_rate'],
            'mileage_rate'            => $unit['mileage_rate'],
            'currency'                => 'CAD',
            'mileage_unit'            => 'km',
            'billing_cycle'           => 'monthly',
            'estimated_mileage'       => '0.00',
            'actual_mileage'          => '0.00',
            'gst_exempt'              => 0,
            'pst_exempt'              => 0,
            'tax_exempt'              => 0,
            'tax_rate_gst'            => $tax['gst'],
            'tax_rate_pst'            => $tax['pst'],
            'tax_rate_hst'            => $tax['hst'],
            'discount_type'           => 'none',
            'discount_value'          => '0.00',
            'insurance_opt_in'        => 0,
            'insurance_cost'          => '0.00',
            'warranty_opt_in'         => 0,
            'warranty_cost'           => '0.00',
            'next_billing_date'       => $l['next_bill'] ?? null,
            'last_billed_date'        => null,
            'notes'                   => $l['label'],
            'created_by'              => RS_USER,
            'updated_by'              => RS_USER,
        ];
        if ($l['status'] === 'completed') {
            $row['closed_at']         = ($l['return'] ?? $l['end']) . ' 16:00:00';
            $row['closed_by_user_id'] = RS_USER;
        }
        $leaseId = db_insert('leases', $row);
        $leaseIds[$lk] = $leaseId;

        // Sync unit status (active→on_lease, completed→available).
        $unitStatus = $l['status'] === 'active' ? 'on_lease' : 'available';
        db_execute("UPDATE equipment_units SET status = ?, updated_by = ? WHERE id = ?", [$unitStatus, RS_USER, $unit['id']]);

        db_insert('lease_status_log', [
            'lease_id'   => $leaseId,
            'old_status' => 'none',
            'new_status' => $l['status'],
            'notes'      => 'Rehearsal seed: ' . $l['label'],
            'changed_by' => 'rehearsal-seeder',
            'user_id'    => RS_USER,
        ]);
        printf("  id=%d %-9s %-32s unit=%s %s/mo\n", $leaseId, $l['status'], $l['label'], $unit['unit_number'], $unit['monthly_rate']);
    }

    // ─────────────────────────────────────────────────────────────────────────────
    // STEP 6 — Invoices (via InvoiceGenerator) + SEND.  Periods are explicit
    // [start,end] inclusive ranges with no gaps/overlaps. 'pay' marks which
    // periods get a payment in Step 7. InvoiceGenerator creates each as 'draft';
    // we immediately SEND every generated invoice (so AR reflects issued invoices
    // per Path-B: outstanding_balance counts sent/partially_paid/overdue).
    // ─────────────────────────────────────────────────────────────────────────────
    echo "\nStep 6 — Invoices...\n";
    $invoicePlan = [
        // lease => [ [start, end, billing_type, invoice_type, pay(bool)], ... ]
        'L1' => [[rs_days_ago(7),   rs_days_ago(0),   'single_period', 'regular', false]],
        'L2' => [[rs_days_ago(60),  rs_days_ago(31),  'partial_start', 'regular', true ],
                 [rs_days_ago(30),  rs_days_ago(0),   'full_month',    'regular', false]],
        'L3' => [[rs_days_ago(45),  rs_days_ago(16),  'partial_start', 'regular', true ],
                 [rs_days_ago(15),  rs_days_ago(0),   'full_month',    'regular', true ]],
        'L4' => [[rs_days_ago(46),  rs_days_ago(17),  'partial_start', 'regular', false],
                 [rs_days_ago(16),  rs_days_ago(0),   'full_month',    'regular', false]],
        'L5' => [[rs_days_ago(180), rs_days_ago(151), 'partial_start', 'regular', true ],
                 [rs_days_ago(150), rs_days_ago(121), 'full_month',    'regular', true ],
                 [rs_days_ago(120), rs_days_ago(91),  'full_month',    'regular', true ],
                 [rs_days_ago(90),  rs_days_ago(61),  'full_month',    'regular', true ],
                 [rs_days_ago(60),  rs_days_ago(31),  'full_month',    'regular', true ],
                 [rs_days_ago(30),  rs_days_ago(0),   'full_month',    'regular', false]],
        'L6' => [[rs_days_ago(38),  rs_days_ago(10),  'single_period', 'final',   true ]],
    ];
    $gen = new \FleetForge\Billing\InvoiceGenerator();
    $invoicesByLease = [];   // lk => [ ['id','total','pay','period_end'], ... ]
    $invoiceTotal = 0;
    foreach ($invoicePlan as $lk => $periods) {
        $leaseId = $leaseIds[$lk];
        $custIdx = $leasePlan[$lk]['cust'];
        $custEmail = strtolower(explode(' ', $customerDefs[$custIdx]['contact'])[0]) . '@' . $customerDefs[$custIdx]['domain'];
        foreach ($periods as [$pStart, $pEnd, $billingType, $invType, $pay]) {
            $res = $gen->createFromLease([
                'lease_id'          => $leaseId,
                'period_start'      => $pStart,
                'period_end'        => $pEnd,
                'billing_type'      => $billingType,
                'invoice_type'      => $invType,
                'generation_source' => 'cron',
                'auto_generated'    => 1,
                'created_by'        => RS_USER,
            ]);
            // Sanity: a rehearsal invoice must never be zero (silent-zero-rate bug class).
            if (bccomp((string) $res['total_amount'], '0.00', 2) <= 0) {
                throw new RuntimeException("ZERO/negative invoice {$res['invoice_number']} for {$lk} {$pStart}->{$pEnd} — rate completeness failure.");
            }
            // Send it (sent_date = the day after the period closed, but never future).
            $sentDate = min($pEnd, rs_days_ago(0));
            rs_send_invoice((int) $res['invoice_id'], $sentDate, $custEmail);
            $invoicesByLease[$lk][] = [
                'id'         => (int) $res['invoice_id'],
                'number'     => $res['invoice_number'],
                'total'      => (string) $res['total_amount'],
                'pay'        => $pay,
                'period_end' => $pEnd,
            ];
            $invoiceTotal++;
            printf("  %-3s %s  %s..%s  $%s%s\n", $lk, $res['invoice_number'], $pStart, $pEnd, $res['total_amount'], $pay ? '  (will pay)' : '');
        }
        // Stamp last_billed_date on active leases = most-recent period end.
        if ($leasePlan[$lk]['status'] === 'active') {
            $lastEnd = end($periods)[1];
            db_execute("UPDATE leases SET last_billed_date = ? WHERE id = ?", [$lastEnd, $leaseId]);
        }
    }
    printf("  Total invoices: %d (all SENT)\n", $invoiceTotal);

    // ─────────────────────────────────────────────────────────────────────────────
    // STEP 7 — Payments (4).  One payment per lease that has paid periods (L2, L3,
    // L5, L6). Each payment is allocated in full to its lease's paid invoices and
    // the invoice is marked 'paid'. Methods mix cheque / EFT(ach) / e-transfer.
    // All amounts CAD (FX 1.0), money via bcmath.
    // ─────────────────────────────────────────────────────────────────────────────
    echo "\nStep 7 — Payments...\n";
    $paymentSpecs = [
        // lease => [method, reference, bank, pay_date]
        'L2' => ['check',      'CHQ-10241',     'RBC',         rs_days_ago(28)],
        'L3' => ['ach',        'EFT-20260530',  'TD Canada',   rs_days_ago(1)],
        'L5' => ['e_transfer', 'ETR-99381',     'BMO',         rs_days_ago(27)],
        'L6' => ['check',      'CHQ-10255',     'RBC',         rs_days_ago(8)],
    ];
    $paySeq = 0;
    foreach ($paymentSpecs as $lk => [$method, $ref, $bank, $payDate]) {
        $custIdx = $leasePlan[$lk]['cust'];
        $custId  = $customerIds[$custIdx];
        $toPay   = array_values(array_filter($invoicesByLease[$lk], fn($iv) => $iv['pay']));
        if (!$toPay) {
            throw new RuntimeException("Payment spec for {$lk} but no payable invoices — invoice plan / payment spec out of sync.");
        }

        // Payment amount = bcmath sum of the invoices it settles.
        $amount = '0.00';
        foreach ($toPay as $iv) {
            $amount = bcadd($amount, $iv['total'], 2);
        }

        $paySeq++;
        $paymentId = db_insert('payments', [
            'payment_number'       => sprintf('PMT-2026-%05d', $paySeq),
            'customer_id'          => $custId,
            'amount'               => $amount,
            'currency'             => 'CAD',
            'exchange_rate_to_cad' => '1.000000',
            'amount_in_cad'        => $amount,
            'payment_method'       => $method,
            'reference_number'     => $ref,
            'bank_name'            => $bank,
            'payment_date'         => $payDate,
            'received_at'          => $payDate . ' 10:00:00',
            'status'               => 'cleared',
            'notes'                => 'Rehearsal seed payment for ' . $lk,
            'recorded_by'          => RS_USER,
        ]);

        // Allocate in full to each paid invoice + mark it paid.
        foreach ($toPay as $iv) {
            db_insert('payment_allocations', [
                'payment_id'      => $paymentId,
                'invoice_id'      => $iv['id'],
                'amount'          => $iv['total'],
                'currency'        => 'CAD',
                'allocation_type' => 'manual',
                'allocated_by'    => RS_USER,
            ]);
            db_execute(
                "UPDATE invoices SET amount_paid = ?, balance_due = '0.00', status = 'paid', paid_date = ? WHERE id = ?",
                [$iv['total'], $payDate, $iv['id']]
            );
        }
        printf("  id=%d %-12s %s  $%s  (%d invoice%s)\n", $paymentId, $method, $lk, $amount, count($toPay), count($toPay) === 1 ? '' : 's');
    }

    // ─────────────────────────────────────────────────────────────────────────────
    // STEP 8 — Bills (3, AP).  One each from the maintenance / parts / fuel vendor.
    // status 'approved' (entered + approved, awaiting payment), NO journal entry
    // (operational-layer-only — see docblock). Tax = BC GST 5% + PST 7% via bcmath.
    // period_id resolved from bill_date (all recent → open periods).
    // ─────────────────────────────────────────────────────────────────────────────
    echo "\nStep 8 — Bills...\n";
    /** Resolve the acc_period id covering a date (bills.period_id is NOT NULL). */
    $periodForDate = function (string $date): int {
        $row = db_row("SELECT id FROM acc_periods WHERE ? BETWEEN start_date AND end_date", [$date]);
        if (!$row) throw new RuntimeException("No acc_period covers {$date}.");
        return (int) $row['id'];
    };
    /** GL expense account id by code (chart of accounts preserved by the wipe). */
    $acctByCode = function (string $code): int {
        $row = db_row("SELECT id FROM acc_accounts WHERE code = ?", [$code]);
        if (!$row) throw new RuntimeException("acc_account code {$code} not found.");
        return (int) $row['id'];
    };
    $billDefs = [
        ['vendor' => 'maintenance', 'acct' => '6010', 'date' => rs_days_ago(20), 'subtotal' => '2450.00', 'desc' => 'Brake + ABS service and annual CVI prep — trailer fleet'],
        ['vendor' => 'parts',       'acct' => '6020', 'date' => rs_days_ago(12), 'subtotal' => '1180.00', 'desc' => 'Replacement LED lighting kits + air lines — restock'],
        ['vendor' => 'fuel',        'acct' => '6040', 'date' => rs_days_ago(6),  'subtotal' => '3675.00', 'desc' => 'Bulk diesel delivery — yard fuel tank top-up'],
    ];
    $billSeq = 0;
    foreach ($billDefs as $b) {
        $billSeq++;
        $subtotal = $b['subtotal'];
        $gst      = bcmul($subtotal, '0.05', 2);    // BC GST 5%
        $pst      = bcmul($subtotal, '0.07', 2);    // BC PST 7%
        $taxTotal = bcadd($gst, $pst, 2);
        $total    = bcadd($subtotal, $taxTotal, 2);
        $billDate = $b['date'];
        $billId = db_insert('acc_bills', [
            'bill_number'        => sprintf('BILL-2026-%05d', $billSeq),
            'vendor_id'          => $vendorIds[$b['vendor']],
            'vendor_bill_number' => sprintf('INV-%s-%04d', strtoupper(substr($b['vendor'], 0, 3)), 1000 + $billSeq),
            'bill_date'          => $billDate,
            'due_date'           => (new DateTime($billDate))->modify('+30 days')->format('Y-m-d'),
            'period_id'          => $periodForDate($billDate),
            'status'             => 'approved',     // entered + approved, awaiting payment (no JE — see docblock)
            'currency'           => 'CAD',
            'subtotal'           => $subtotal,
            'tax_gst_amount'     => $gst,
            'tax_pst_amount'     => $pst,
            'tax_total'          => $taxTotal,
            'total_amount'       => $total,
            'amount_paid'        => '0.00',
            'balance_due'        => $total,
            'notes'              => $b['desc'],
            'created_by'         => RS_USER,
        ]);
        db_insert('acc_bill_lines', [
            'bill_id'        => $billId,
            'account_id'     => $acctByCode($b['acct']),
            'description'    => $b['desc'],
            'quantity'       => '1.0000',
            'unit_cost'      => $subtotal,
            'amount'         => $subtotal,
            'tax_gst_amount' => $gst,
            'tax_pst_amount' => $pst,
            'sort_order'     => 1,
        ]);
        printf("  id=%d %-12s $%s (sub %s + tax %s)  due %s\n", $billId, $b['vendor'], $total, $subtotal, $taxTotal, (new DateTime($billDate))->modify('+30 days')->format('Y-m-d'));
    }

    // ─────────────────────────────────────────────────────────────────────────────
    // STEP 9 — Recompute denormalized counters (Path-B semantics, per project memory
    // project_path_b_counter_semantics + scripts/demo_seed.php).
    //   customers.outstanding_balance = SUM(balance_due) of invoices in
    //     status IN ('sent','partially_paid','overdue) — drafts/voids excluded.
    //   customers.total_revenue       = SUM(amount_paid).
    //   equipment_units.lease_count / total_revenue recomputed from leases/invoices.
    //   vendors.total_spent           = SUM of paid bills (all approved-unpaid → 0).
    // ─────────────────────────────────────────────────────────────────────────────
    echo "\nStep 9 — Recomputing counters...\n";
    db_execute(
        "UPDATE customers c SET
            lease_count = (SELECT COUNT(*) FROM leases WHERE customer_id = c.id AND deleted_at IS NULL),
            active_lease_count = (SELECT COUNT(*) FROM leases WHERE customer_id = c.id AND status = 'active' AND deleted_at IS NULL),
            total_revenue = COALESCE((SELECT SUM(amount_paid) FROM invoices WHERE customer_id = c.id AND deleted_at IS NULL), 0),
            outstanding_balance = COALESCE((SELECT SUM(balance_due) FROM invoices WHERE customer_id = c.id AND deleted_at IS NULL AND status IN ('sent','partially_paid','overdue')), 0)
          WHERE deleted_at IS NULL",
        []
    );
    db_execute(
        "UPDATE equipment_units eu SET
            lease_count = (SELECT COUNT(*) FROM leases WHERE equipment_unit_id = eu.id AND deleted_at IS NULL),
            total_revenue = COALESCE(
              (SELECT SUM(i.amount_paid) FROM invoices i
                 JOIN leases l ON l.id = i.lease_id
                WHERE l.equipment_unit_id = eu.id AND i.deleted_at IS NULL), 0)
          WHERE deleted_at IS NULL",
        []
    );
    db_execute(
        "UPDATE vendors v SET total_spent = COALESCE(
            (SELECT SUM(amount_paid) FROM acc_bills WHERE vendor_id = v.id), 0)
          WHERE deleted_at IS NULL",
        []
    );
    echo "  Counters recomputed (customers / equipment / vendors).\n";

    // ─────────────────────────────────────────────────────────────────────────────
    // Summary
    // ─────────────────────────────────────────────────────────────────────────────
    echo "\n=== Summary ===\n";
    foreach (['equipment_templates','equipment_units','customers','vendors','leases','invoices','payments','acc_bills'] as $t) {
        printf("  %-20s %d\n", $t, (int) db_row("SELECT COUNT(*) n FROM {$t}", [])['n']);
    }
    $ar  = db_row("SELECT COALESCE(SUM(balance_due),0) t FROM invoices WHERE deleted_at IS NULL AND status IN ('sent','partially_paid','overdue')", [])['t'];
    $rev = db_row("SELECT COALESCE(SUM(amount_paid),0) t FROM invoices WHERE deleted_at IS NULL", [])['t'];
    $ap  = db_row("SELECT COALESCE(SUM(balance_due),0) t FROM acc_bills", [])['t'];
    printf("  Outstanding AR (sent+): $%s\n", number_format((float) $ar, 2));
    printf("  Collected (paid):       $%s\n", number_format((float) $rev, 2));
    printf("  Outstanding AP (bills): $%s\n", number_format((float) $ap, 2));
    echo "\n=== Rehearsal seed complete ===\n";

}
