/** Date N days before today, as Y-m-d. */
function rs_days_ago(int $n): string { return (new DateTime())->modify("-{$n} days")->format('Y-m-d'); }

/** Date N days after today, as Y-m-d. */
function rs_days_from_now(int $n): string { return (new DateTime())->modify("+{$n} days")->format('Y-m-d'); }

/**
 * Freeze a customer's tax rates onto a lease/invoice snapshot.
 * All rehearsal customers are BC-taxable (tax_rate_id=1, no exemptions), so
 * this returns the raw gst/pst/hst rates from tax_rates unchanged.
 *
 * @return array{gst:string,pst:string,hst:string}
 */
function rs_freeze_tax(int $taxRateId): array
{
    $row = db_row("SELECT gst_rate, pst_rate, hst_rate FROM tax_rates WHERE id = ?", [$taxRateId]);
    if (!$row) {
        throw new RuntimeException("tax_rate id={$taxRateId} not found — wipe preserves tax_rates, so this is a real problem.");
    }
    return ['gst' => $row['gst_rate'], 'pst' => $row['pst_rate'], 'hst' => $row['hst_rate']];
}

/**
 * Build the equipment_snapshot_json a lease freezes at creation.
 * Mirrors scripts/demo_seed.php::buildEquipSnap so the lease snapshot shape
 * matches the rest of the system.
 */
function rs_build_equip_snap(array $u): string
{
    return json_encode([
        'vin'                => $u['vin'],
        'year'               => $u['year'] ? (int) $u['year'] : null,
        'category'           => $u['category'],
        'width_ft'           => $u['width_ft'],
        'height_ft'          => $u['height_ft'],
        'length_ft'          => $u['length_ft'],
        'axle_count'         => $u['axle_count'] ? (int) $u['axle_count'] : null,
        'unit_number'        => $u['unit_number'],
        'license_plate'      => $u['license_plate'],
        'license_state'      => $u['license_state'],
        'template_name'      => $u['template_name'],
        'tracking_provider'  => $u['tracking_provider'],
        'mileage_at_snapshot'=> (int) ($u['mileage'] ?? 0),
        'weight_capacity_lbs'=> $u['weight_capacity_lbs'] ? (int) $u['weight_capacity_lbs'] : null,
    ]);
}

/** Mark an invoice as SENT via direct UPDATE (no AutoEntryBridge / no JE — see docblock). */
function rs_send_invoice(int $invoiceId, string $sentDate, ?string $toEmail): void
{
    db_execute(
        "UPDATE invoices
            SET status = 'sent', sent_date = ?, sent_at = ?, sent_by = ?,
                delivery_method = 'email', sent_to_email = ?
          WHERE id = ?",
        [$sentDate, $sentDate . ' 09:00:00', RS_USER, $toEmail, $invoiceId]
    );
}

